const I18N = (() => {
  const LOCALES = {en: 'en-US', it: 'it-IT', es: 'es-ES', de: 'de-DE', fr: 'fr-FR'};
  let lang = 'en';
  const rules = {};
  const escText = s => String(s ?? '').replace(/[&<>"']/g, ch => ({'&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;'}[ch]));

  class Html { constructor(s){ this.s = String(s); } }

  function lookup(key, params){
    let v = I18N_STRINGS[lang][key];
    if (v === undefined) v = I18N_STRINGS.en[key];
    if (v === undefined){ console.warn('i18n: missing key ' + key); return key; }
    if (typeof v === 'object'){
      const n = Number(params && params.n);
      const r = rules[lang] || (rules[lang] = new Intl.PluralRules(LOCALES[lang]));
      v = v[r.select(Number.isFinite(n) ? n : 0)] ?? v.other;
    }
    return v;
  }
  const fill = (tpl, params, map) => tpl.replace(/\{(\w+)\}/g, (m, name) =>
    params && params[name] !== undefined ? map(params[name]) : m);

  return {
    /** Set the language ('en' | 'it'); returns true if it changed. */
    setLang(l){
      l = I18N_STRINGS[l] ? l : 'en';
      document.documentElement.lang = l;
      if (l === lang) return false;
      lang = l;
      return true;
    },
    get lang(){ return lang; },
    get locale(){ return LOCALES[lang]; },
    /** Mark a parameter as trusted markup for tx(). */
    html: s => new Html(s),
    t(key, params){ return fill(lookup(key, params), params, v => v instanceof Html ? v.s : String(v)); },
    /** HTML-safe version of t(): the text and every parameter are escaped, except I18N.html() values. */
    tx(key, params){ return fill(escText(lookup(key, params)), params, v => v instanceof Html ? v.s : escText(v)); },
    // ---------- formatting ----------
    time: ts => new Date(ts * 1000).toLocaleTimeString(LOCALES[lang], {hour: '2-digit', minute: '2-digit'}),
    weekdayTime: ts => new Date(ts * 1000).toLocaleString(LOCALES[lang], {weekday: 'short', hour: '2-digit', minute: '2-digit'}),
    dateTime: ts => new Date(ts * 1000).toLocaleString(LOCALES[lang], {dateStyle: 'medium', timeStyle: 'short'}),
    weekdayNarrow: ts => new Date(ts * 1000).toLocaleDateString(LOCALES[lang], {weekday: 'narrow'}),
    number: (n, digits = 0) => Number(n).toLocaleString(LOCALES[lang], {maximumFractionDigits: digits}),
    /** Fill [data-i18n], [data-i18n-html], [data-i18n-title] and [data-i18n-placeholder] inside root. */
    apply(root = document){
      root.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = this.t(el.dataset.i18n); });
      root.querySelectorAll('[data-i18n-html]').forEach(el => { el.innerHTML = lookup(el.dataset.i18nHtml); });
      root.querySelectorAll('[data-i18n-title]').forEach(el => { el.title = this.t(el.dataset.i18nTitle); });
      root.querySelectorAll('[data-i18n-placeholder]').forEach(el => { el.placeholder = this.t(el.dataset.i18nPlaceholder); });
    },
  };
})();

